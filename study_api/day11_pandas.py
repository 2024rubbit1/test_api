import pandas as pd

df = pd.DataFrame({
    '用例ID': ['TC001', 'TC002', 'TC003', 'TC004', 'TC005'],
    '模块': ['登录', '产品', '入库', '出库', '结算'],
    '优先级': ['高', '中', '高', '低', '中'],
    '预期结果': ['登录成功', '新增产品成功', '新增入库成功', '新建出库成功', '结算无误'],
    '实际结果': ['通过', '失败', '通过', '通过', '未执行']
})
print(df)
# 条件：实际结果等于“失败”
condition = df['实际结果'] == '失败'
print(condition)          # 这是一个布尔 Series，True/False
print(df[condition])      # 把布尔 Series 放进 df[] 中，返回符合条件的行

# 更简洁的写法（一步到位）
print(df[df['实际结果'] == '失败'])
# 两个条件必须同时满足，用 & 连接，每个条件要用括号括起来
print(df[(df["优先级"] == "高") & (df["实际结果"] == "失败")])
print(df[(df["优先级"] == "高") | (df["实际结果"] == "未执行")])
print(df[df['实际结果'] != '通过'])

# 找出“模块”列中包含“入”字的用例（比如入库）
print(df[df['模块'].str.contains('入')])

# 找出“预期结果”中以“新增”开头的用例
print(df[df['预期结果'].str.startswith('新增')])

# 统计失败的用例数量
print((df['实际结果'] == '失败').sum())

# 统计每个优先级的失败用例数
print(df[df['实际结果'] == '失败']['优先级'].value_counts())

print(df[df["实际结果"] == "通过"])
print(df[df["优先级"] == "高"])
print(df[(df["优先级"] == "高") & (df['实际结果'] == '失败')])
print(df[(df["优先级"] == "中") | (df['实际结果'] == '未执行')])
print(df[df["模块"].str.contains("入")])

print((df["实际结果"] == "失败").sum())
print(df[df["实际结果"] == "失败"][["用例ID", "模块"]])
print(df[(df["预期结果"].str.contains("成功")) & (df["实际结果"] != "通过")])
